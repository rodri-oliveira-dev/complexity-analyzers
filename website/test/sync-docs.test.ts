import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { readdir, readFile } from 'node:fs/promises';
import { promisify } from 'node:util';
import { describe, expect, it } from 'vitest';

const exec = promisify(execFile);
const root = new URL('../', import.meta.url);
const docs = new URL('../src/content/docs/', import.meta.url);

const digest = async (path: string) => createHash('sha256').update(await readFile(new URL(path, docs))).digest('hex');

describe('documentation synchronization', () => {
  it('generates localized pages with source ownership metadata', async () => {
    const [english, portuguese] = await Promise.all([
      readFile(new URL('analyzer/diagnostics.md', docs), 'utf8'),
      readFile(new URL('pt-br/analyzer/diagnostics.md', docs), 'utf8')
    ]);
    expect(english).toContain('text: Source synced');
    expect(portuguese).toContain('text: Fonte sincronizada');
    expect(english).toContain('Generated by scripts/sync-docs.mjs from docs/en/analyzers.md');
    expect(portuguese).toContain('Generated by scripts/sync-docs.mjs from docs/pt-BR/analyzers.md');
  });

  it('rewrites mapped cross-document links to localized portal routes', async () => {
    const [english, portuguese] = await Promise.all([
      readFile(new URL('reference/architecture.md', docs), 'utf8'),
      readFile(new URL('pt-br/reference/architecture.md', docs), 'utf8')
    ]);
    expect(english).toContain('/complexity-analyzers/analyzer/configuration/');
    expect(portuguese).toContain('/complexity-analyzers/pt-br/analyzer/configuration/');
  });

  it('generates bilingual GitHub Action references and rewrites CLI links', async () => {
    const [english, portuguese] = await Promise.all([
      readFile(new URL('action/reference.md', docs), 'utf8'),
      readFile(new URL('pt-br/action/reference.md', docs), 'utf8')
    ]);
    expect(english).toContain('Generated by scripts/sync-docs.mjs from docs/en/github-action.md');
    expect(portuguese).toContain('Generated by scripts/sync-docs.mjs from docs/pt-BR/github-action.md');
    expect(english).toContain('/complexity-analyzers/cli/reference/');
    expect(portuguese).toContain('/complexity-analyzers/pt-br/cli/reference/');
  });

  it('is deterministic across repeated runs', async () => {
    const before = await digest('mcp/reference.md');
    await exec(process.execPath, ['scripts/sync-docs.mjs'], { cwd: new URL('.', root) });
    expect(await digest('mcp/reference.md')).toBe(before);
    const generatedDirectory = await readdir(new URL('mcp/', docs));
    expect(generatedDirectory.some((name) => name.endsWith('.tmp'))).toBe(false);
  });
});
